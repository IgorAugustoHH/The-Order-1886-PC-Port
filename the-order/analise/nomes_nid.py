def nid(nome):
    d = hashlib.sha1(nome.encode() + bytes.fromhex('518d64a635ded8c1e6b039b1c3e55230')).digest()[:8][::-1]
    return base64.b64encode(d).decode().rstrip('=').replace('/', '-')


